export function getLocationBySlug(slug: string): LocationState | undefined {
  if (!slug) return undefined;
  const clean = slug.toLowerCase().trim();
  return NIGERIA_LOCATIONS.find((loc) => loc.slug === clean || loc.name.toLowerCase() === clean);
}

export function getCityBySlug(location: LocationState, citySlug: string): LocationCity | undefined {
  if (!location || !citySlug) return undefined;
  const clean = citySlug.toLowerCase().trim();
  return location.majorCities.find((c) => c.slug === clean || c.name.toLowerCase() === clean);
}
